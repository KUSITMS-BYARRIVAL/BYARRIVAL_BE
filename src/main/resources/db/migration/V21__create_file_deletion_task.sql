-- ---------- 저장소 파일 삭제 작업 (MY-02·MY-10) ----------
-- 지워야 할 S3 파일(바꾸거나 지운 프로필 이미지, 파기한 회원의 프로필 이미지)을 DB 변경과 같은 트랜잭션에서 남긴다.
-- 작업자가 주기적으로 지우고, 지운 뒤에만 행을 없앤다. 삭제에 실패하면 행이 남아 다음 주기에 다시 시도한다.
-- 그래서 S3 장애나 서버 재시작이 있어도 파기한 회원의 사진이 저장소에 남지 않는다.
CREATE TABLE file_deletion_task (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url            VARCHAR(500) NOT NULL,
    attempts       INTEGER      NOT NULL DEFAULT 0,
    last_failed_at TIMESTAMP,
    created_at     TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),
    updated_at     TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul')
);
