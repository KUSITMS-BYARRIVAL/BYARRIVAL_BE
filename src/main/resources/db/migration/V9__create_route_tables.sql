-- 노선 생성·후보 카드 담기 (RIDE-03, RIDE-04, RIDE-07~10)
--  - route: 서비스일당 1개. 만료는 expires_at(생성 서비스일 다음 날 04:00)과 비교해 판단한다
--  - route_card: 노선 생성 시 고정한 후보 카드 풀 스냅샷과 사용자가 담은 순서
--  - condition_history: 사용자 컨디션 이력 (추후 개인화 기초 데이터)
--  - recommendation_log: 추천 입력 조건·후보 수·폴백 단계·선택 결과·담은 카드. 0건 결과도 남겨 route_id가 NULL일 수 있다

CREATE TABLE route (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    service_date    DATE        NOT NULL,
    route_condition VARCHAR(10) NOT NULL,
    target_minutes  INT         NOT NULL,                                -- 목표 시간 T(분)
    status          VARCHAR(20) NOT NULL DEFAULT 'CREATED',
    fallback_step   INT         NOT NULL,                                -- 0: 확정, 1: 폴백 1, 2: 폴백 2
    expires_at      TIMESTAMP   NOT NULL,
    boarded_at      TIMESTAMP,                                           -- 시작하기(보딩패스 이동) 시각
    started_at      TIMESTAMP,                                           -- 출발하기 시각 (RIDE-06)
    completed_at    TIMESTAMP,                                           -- 완주 시각 (ARR-01)
    created_at      TIMESTAMP   NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),
    updated_at      TIMESTAMP   NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),

    CONSTRAINT uk_route_user_service_date UNIQUE (user_id, service_date),
    CONSTRAINT ck_route_condition CHECK (route_condition IN ('SUNNY', 'NORMAL', 'CLOUDY', 'RAINY')),
    CONSTRAINT ck_route_status CHECK (status IN ('CREATED', 'BOARDING', 'IN_PROGRESS', 'COMPLETED')),
    CONSTRAINT ck_route_fallback_step CHECK (fallback_step BETWEEN 0 AND 2),
    CONSTRAINT ck_route_target_minutes CHECK (target_minutes > 0)
);

CREATE TABLE route_card (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id        BIGINT        NOT NULL REFERENCES route (id) ON DELETE CASCADE,
    article_id      BIGINT        NOT NULL REFERENCES article (id),
    pool_order      INT           NOT NULL,                              -- 후보 카드 순번 (1부터)
    difficulty      VARCHAR(10)   NOT NULL,                              -- 생성 시점 난이도 스냅샷
    reading_minutes NUMERIC(7, 3) NOT NULL,                              -- 생성 시점 예상 읽기시간 스냅샷
    recommended     BOOLEAN       NOT NULL,                              -- 추천 구성 기사 여부 (나머지는 보충 후보)
    cart_order      INT,                                                 -- 담은 순서. 담지 않았으면 NULL
    carted_at       TIMESTAMP,
    created_at      TIMESTAMP     NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),
    updated_at      TIMESTAMP     NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),

    CONSTRAINT uk_route_card_article UNIQUE (route_id, article_id),
    CONSTRAINT uk_route_card_pool_order UNIQUE (route_id, pool_order),
    CONSTRAINT ck_route_card_difficulty CHECK (difficulty IN ('HARD', 'EASY')),
    CONSTRAINT ck_route_card_cart CHECK ((cart_order IS NULL) = (carted_at IS NULL))
);
CREATE UNIQUE INDEX uk_route_card_cart_order ON route_card (route_id, cart_order) WHERE cart_order IS NOT NULL;
-- 출근길 공감대(HOME-05) 집계: 서비스일별 기사를 담은 사용자 수
CREATE INDEX ix_route_card_article_carted ON route_card (article_id) WHERE cart_order IS NOT NULL;

CREATE TABLE condition_history (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    service_date    DATE        NOT NULL,
    route_condition VARCHAR(10) NOT NULL,
    route_id        BIGINT      NOT NULL REFERENCES route (id) ON DELETE CASCADE,
    created_at      TIMESTAMP   NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),
    updated_at      TIMESTAMP   NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),

    CONSTRAINT uk_condition_history_route UNIQUE (route_id),
    CONSTRAINT ck_condition_history_condition CHECK (route_condition IN ('SUNNY', 'NORMAL', 'CLOUDY', 'RAINY'))
);
CREATE INDEX ix_condition_history_user ON condition_history (user_id, service_date);

CREATE TABLE recommendation_log (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id              BIGINT        REFERENCES route (id) ON DELETE CASCADE,
    user_id               BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    service_date          DATE          NOT NULL,
    route_condition       VARCHAR(10)   NOT NULL,
    target_minutes        INT           NOT NULL,
    interest_category_ids BIGINT[]      NOT NULL,
    candidate_count       INT           NOT NULL,
    candidate_hard_count  INT           NOT NULL,
    candidate_easy_count  INT           NOT NULL,
    fallback_step         INT,                                           -- 0건이면 NULL
    selected_article_ids  BIGINT[]      NOT NULL,                        -- 추천 구성 기사 (선택 순서)
    selected_hard_count   INT           NOT NULL,
    selected_easy_count   INT           NOT NULL,
    selected_minutes      NUMERIC(8, 3) NOT NULL,
    pool_size             INT           NOT NULL,
    cart_article_ids      BIGINT[],                                      -- 시작하기 시점에 담은 카드 (담은 순서)
    cart_minutes          NUMERIC(8, 3),
    boarded_at            TIMESTAMP,
    created_at            TIMESTAMP     NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),
    updated_at            TIMESTAMP     NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),

    CONSTRAINT ck_recommendation_log_condition CHECK (route_condition IN ('SUNNY', 'NORMAL', 'CLOUDY', 'RAINY'))
);
CREATE UNIQUE INDEX uk_recommendation_log_route ON recommendation_log (route_id) WHERE route_id IS NOT NULL;
CREATE INDEX ix_recommendation_log_created_at ON recommendation_log (created_at);
