-- 어드민의 기사 숨김·복구 이력 (ARTICLE-04, ARTICLE-05)
--  - 숨김은 사유가 필수이고, 기타 사유는 메모도 필수다
-- =========================================================

CREATE TABLE article_visibility_history (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id BIGINT       NOT NULL REFERENCES article (id) ON DELETE CASCADE,
    admin_id   BIGINT       NOT NULL REFERENCES admin_account (id),
    action     VARCHAR(20)  NOT NULL,
    reason     VARCHAR(20),
    memo       VARCHAR(100),
    created_at TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),

    CONSTRAINT ck_article_visibility_history_action CHECK (action IN ('HIDE', 'RESTORE')),
    CONSTRAINT ck_article_visibility_history_reason CHECK (reason IN ('COPYRIGHT', 'CORRECTION', 'QUALITY', 'ETC')),
    CONSTRAINT ck_article_visibility_history_hide CHECK (action <> 'HIDE' OR reason IS NOT NULL),
    CONSTRAINT ck_article_visibility_history_restore CHECK (action <> 'RESTORE' OR (reason IS NULL AND memo IS NULL)),
    CONSTRAINT ck_article_visibility_history_etc CHECK (reason IS DISTINCT FROM 'ETC' OR memo IS NOT NULL)
);
CREATE INDEX ix_article_visibility_history_article ON article_visibility_history (article_id, id DESC);
