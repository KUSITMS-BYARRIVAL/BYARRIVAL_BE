-- 수신 설정은 알림 유형이 아니라 설정 화면의 카테고리 단위로 저장한다. 지금은 ACTIVITY(행동 유도 알림 전체) 하나다.
ALTER TABLE user_notification_setting RENAME COLUMN notification_type TO category;
ALTER TABLE user_notification_setting RENAME CONSTRAINT uk_user_notification_setting TO uk_user_notification_setting_category;
ALTER TABLE user_notification_setting
    ADD CONSTRAINT ck_user_notification_setting_category CHECK (category IN ('ACTIVITY'));

-- 푸시를 받을 기기의 FCM 토큰. 한 사용자가 여러 기기를 가질 수 있고, 토큰 하나는 한 사용자에게만 속한다.
CREATE TABLE device_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token      VARCHAR(512) NOT NULL,
    platform   VARCHAR(10)  NOT NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),
    updated_at TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),

    CONSTRAINT uk_device_token_token UNIQUE (token),
    CONSTRAINT ck_device_token_platform CHECK (platform IN ('ANDROID', 'IOS'))
);
CREATE INDEX idx_device_token_user ON device_token (user_id);

-- 알림함. 보낸 알림은 푸시 여부와 상관없이 모두 저장하고 30일 뒤 삭제한다.
CREATE TABLE notification (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type         VARCHAR(30)  NOT NULL,
    title        VARCHAR(100) NOT NULL,
    body         VARCHAR(500) NOT NULL,
    params       TEXT         NOT NULL DEFAULT '{}',                    -- 화면 이동에 필요한 값 (JSON 문자열 맵)
    service_date DATE         NOT NULL,                                 -- 보낸 시각의 서비스일 (04:00 기준)
    push_status  VARCHAR(20)  NOT NULL,
    read_at      TIMESTAMP,
    created_at   TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),
    updated_at   TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),

    CONSTRAINT ck_notification_type CHECK (type IN (
        'ROUTE_READY', 'ROUTE_INCOMPLETE', 'STREAK_MILESTONE', 'SMALLTALK', 'STREAK_BREAK', 'POPULAR_ARTICLE',
        'SERVICE_NOTICE', 'TEST')),
    CONSTRAINT ck_notification_push_status CHECK (push_status IN ('PENDING', 'SENT', 'FAILED', 'SKIPPED', 'NO_DEVICE'))
);
CREATE INDEX idx_notification_user_id ON notification (user_id, id DESC);
CREATE INDEX idx_notification_user_unread ON notification (user_id) WHERE read_at IS NULL;
CREATE INDEX idx_notification_created_at ON notification (created_at);
-- 운영 안내·테스트를 뺀 알림은 서비스일마다 유형별로 한 번만 보낸다. 블루/그린 전환 중 중복 발송도 막는다.
CREATE UNIQUE INDEX uk_notification_daily_type ON notification (user_id, type, service_date)
    WHERE type NOT IN ('SERVICE_NOTICE', 'TEST');
