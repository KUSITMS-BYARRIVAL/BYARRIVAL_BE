-- =========================================================
-- 회원 이용 제한 (MEMBER-03)
--  - 운영자가 기간과 사유를 정해 제한하고, 한 번 남긴 조치는 이력으로 둔다
--  - ends_at이 비어 있으면 영구 제한이다. 기간이 지나면 따로 해제하지 않아도 풀린다
--  - 운영자가 직접 해제하면 released_at과 해제한 운영자를 남긴다
--  - 회원을 파기하면 제한 이력도 함께 지운다
-- =========================================================

CREATE TABLE user_restriction (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    admin_id             BIGINT       NOT NULL REFERENCES admin_account (id),
    period               VARCHAR(20)  NOT NULL,
    reason               VARCHAR(100) NOT NULL,
    starts_at            TIMESTAMP    NOT NULL,
    ends_at              TIMESTAMP,
    released_at          TIMESTAMP,
    released_by_admin_id BIGINT REFERENCES admin_account (id),
    CONSTRAINT ck_user_restriction_period CHECK (period IN ('DAYS_3', 'DAYS_7', 'DAYS_30', 'PERMANENT')),
    CONSTRAINT ck_user_restriction_ends_at CHECK (ends_at IS NULL OR ends_at > starts_at),
    CONSTRAINT ck_user_restriction_released CHECK ((released_at IS NULL) = (released_by_admin_id IS NULL))
);
CREATE INDEX ix_user_restriction_user ON user_restriction (user_id, starts_at DESC);
