-- ---------- 회원 직군 (기능명세 2026-11-08, ONB-11·MY-11) ----------
-- 직군은 1~2개를 고른다. 학생은 희망 직군이다.
-- sort_order는 고른 순서이며 홈 "지금 출근길에서 많이 봐요"의 직군 칩 순서가 된다(HOME-05).
CREATE TABLE user_job_group (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    job_group  VARCHAR(30) NOT NULL,
    sort_order SMALLINT    NOT NULL,
    created_at TIMESTAMP   NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),
    updated_at TIMESTAMP   NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),

    CONSTRAINT ck_user_job_group_code CHECK (job_group IN (
        'PLANNING_MARKETING', 'HR_ADMIN_LEGAL', 'FINANCE_ACCOUNTING', 'IT_DATA',
        'DESIGN', 'SALES_SERVICE', 'MANUFACTURING_LOGISTICS', 'MEDICAL',
        'RESEARCH_EDUCATION', 'MEDIA_CULTURE_SPORTS', 'PUBLIC_WELFARE', 'ETC_FREELANCE')),
    -- 최대 2개: 순서는 1, 2만 허용하고 사용자마다 순서가 겹치지 않는다
    CONSTRAINT ck_user_job_group_order CHECK (sort_order IN (1, 2)),
    CONSTRAINT uk_user_job_group       UNIQUE (user_id, job_group),
    CONSTRAINT uk_user_job_group_order UNIQUE (user_id, sort_order)
);
-- 직군별 집계(HOME-05)용
CREATE INDEX ix_user_job_group_job_group ON user_job_group (job_group);
