-- =========================================================
-- 어드민 알림 발송 (NOTI-01·02)
--  - 운영자가 공지·이벤트 알림을 즉시 또는 예약으로 보낸다. 한 번의 발송을 한 행으로 남긴다
--  - status: SCHEDULED(예약·발송 대기) → SENDING → COMPLETED 또는 FAILED. 발송 전에는 CANCELED로 취소할 수 있다
--  - recipient_count: 발송을 시작할 때 실제로 보낸 회원 수(수신 설정을 끈 사람·미동의자 제외)
--  - success_count·failure_count: 푸시 결과. 기기가 없거나 보내지 못하면 실패로 센다
--  - 공지는 SERVICE_NOTICE, 이벤트는 새 유형 EVENT로 알림함에 남긴다. 둘 다 유형별 하루 1번 제약에서 뺀다
-- =========================================================

CREATE TABLE notification_broadcast (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id        BIGINT       NOT NULL REFERENCES admin_account (id),
    kind            VARCHAR(20)  NOT NULL,
    target          VARCHAR(20)  NOT NULL,
    title           VARCHAR(20)  NOT NULL,
    body            VARCHAR(60)  NOT NULL,
    screen          VARCHAR(30)  NOT NULL,
    url             VARCHAR(500),
    scheduled_at    TIMESTAMP    NOT NULL,
    status          VARCHAR(20)  NOT NULL,
    recipient_count INTEGER,
    success_count   INTEGER      NOT NULL DEFAULT 0,
    failure_count   INTEGER      NOT NULL DEFAULT 0,
    started_at      TIMESTAMP,
    completed_at    TIMESTAMP,
    created_at      TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),
    updated_at      TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),

    CONSTRAINT ck_notification_broadcast_kind CHECK (kind IN ('NOTICE', 'EVENT')),
    CONSTRAINT ck_notification_broadcast_target CHECK (target IN ('ALL', 'WORKER', 'STUDENT', 'ETC')),
    CONSTRAINT ck_notification_broadcast_screen CHECK (screen IN ('HOME', 'TODAY_ROUTE', 'TODAY_SMALLTALK',
        'MY_RECORD', 'NOTICE')),
    CONSTRAINT ck_notification_broadcast_url CHECK ((screen = 'NOTICE') = (url IS NOT NULL)),
    CONSTRAINT ck_notification_broadcast_status CHECK (status IN ('SCHEDULED', 'SENDING', 'COMPLETED', 'FAILED',
        'CANCELED'))
);
CREATE INDEX ix_notification_broadcast_due ON notification_broadcast (scheduled_at) WHERE status = 'SCHEDULED';
CREATE INDEX ix_notification_broadcast_scheduled ON notification_broadcast (scheduled_at DESC);

ALTER TABLE notification DROP CONSTRAINT ck_notification_type;
ALTER TABLE notification ADD CONSTRAINT ck_notification_type CHECK (type IN (
    'ROUTE_READY', 'ROUTE_INCOMPLETE', 'STREAK_MILESTONE', 'SMALLTALK', 'STREAK_BREAK', 'POPULAR_ARTICLE',
    'SERVICE_NOTICE', 'EVENT', 'MARKETING_CONSENT', 'TEST'));

DROP INDEX uk_notification_daily_type;
CREATE UNIQUE INDEX uk_notification_daily_type ON notification (user_id, type, service_date)
    WHERE type NOT IN ('SERVICE_NOTICE', 'EVENT', 'MARKETING_CONSENT', 'TEST');
