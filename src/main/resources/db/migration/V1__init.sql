-- =========================================================
-- Byarrival 스키마 v1 (PostgreSQL)
--  - PK: BIGINT IDENTITY (JPA GenerationType.IDENTITY 호환)
--  - 시각: TIMESTAMP (KST 기준 LocalDateTime 저장)
--  - 상태값: CHECK 제약으로 허용값 고정
--  - updated_at 자동 갱신은 JPA(@LastModifiedDate)에서 처리
-- =========================================================

-- ---------- 회원 ----------

CREATE TABLE users (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider                VARCHAR(20)  NOT NULL,                       -- 소셜 Provider (ONB-02 확정 필요)
    provider_user_id        VARCHAR(255) NOT NULL,                       -- 소셜 계정 식별자
    nickname                VARCHAR(30),                                 -- 닉네임 (ONB-04 글자수 확정 필요)
    profile_image_url       VARCHAR(500),                                -- 프로필 이미지 URL (MY-02)
    travel_type             VARCHAR(20),                                 -- 이동 유형 (ONB-05)
    commute_start_time      TIME,                                        -- 이동 시작 시각 (ONB-06)
    default_commute_minutes INT,                                         -- 기본 이동시간(분) (ONB-08, MY-05)
    mon_minutes             INT,                                         -- 요일별 이동시간(분), 0 = 쉬는 날
    tue_minutes             INT,
    wed_minutes             INT,
    thu_minutes             INT,
    fri_minutes             INT,
    sat_minutes             INT,
    sun_minutes             INT,
    onboarding_status       VARCHAR(20)  NOT NULL DEFAULT 'IN_PROGRESS', -- (ONB-10)
    onboarded_at            TIMESTAMP,
    status                  VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',      -- (MY-10)
    withdrawn_at            TIMESTAMP,                                   -- 탈퇴 시각 (+6개월 후 파기)
    created_at              TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at              TIMESTAMP    NOT NULL DEFAULT now(),

    CONSTRAINT ck_users_travel_type       CHECK (travel_type IN ('WORKER', 'STUDENT', 'ETC')),
    CONSTRAINT ck_users_onboarding_status CHECK (onboarding_status IN ('IN_PROGRESS', 'COMPLETED')),
    CONSTRAINT ck_users_status            CHECK (status IN ('ACTIVE', 'WITHDRAWN')),
    CONSTRAINT ck_users_onboarded_at      CHECK (onboarding_status <> 'COMPLETED' OR onboarded_at IS NOT NULL),
    CONSTRAINT ck_users_withdrawn_at      CHECK (status <> 'WITHDRAWN' OR withdrawn_at IS NOT NULL),
    CONSTRAINT ck_users_default_minutes   CHECK (default_commute_minutes BETWEEN 0 AND 120 AND default_commute_minutes % 5 = 0),
    CONSTRAINT ck_users_mon_minutes       CHECK (mon_minutes BETWEEN 0 AND 120 AND mon_minutes % 5 = 0),
    CONSTRAINT ck_users_tue_minutes       CHECK (tue_minutes BETWEEN 0 AND 120 AND tue_minutes % 5 = 0),
    CONSTRAINT ck_users_wed_minutes       CHECK (wed_minutes BETWEEN 0 AND 120 AND wed_minutes % 5 = 0),
    CONSTRAINT ck_users_thu_minutes       CHECK (thu_minutes BETWEEN 0 AND 120 AND thu_minutes % 5 = 0),
    CONSTRAINT ck_users_fri_minutes       CHECK (fri_minutes BETWEEN 0 AND 120 AND fri_minutes % 5 = 0),
    CONSTRAINT ck_users_sat_minutes       CHECK (sat_minutes BETWEEN 0 AND 120 AND sat_minutes % 5 = 0),
    CONSTRAINT ck_users_sun_minutes       CHECK (sun_minutes BETWEEN 0 AND 120 AND sun_minutes % 5 = 0)
);
-- 활성 회원 기준으로만 소셜 계정 중복 금지 (탈퇴 후 재가입 허용)
CREATE UNIQUE INDEX uk_users_provider_active ON users (provider, provider_user_id) WHERE status = 'ACTIVE';

CREATE TABLE refresh_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash VARCHAR(255) NOT NULL UNIQUE,                             -- 원문 저장 안 함
    expires_at TIMESTAMP    NOT NULL,
    revoked_at TIMESTAMP,                                                -- 로그아웃·탈퇴 시 폐기
    created_at TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX ix_refresh_token_user ON refresh_token (user_id);

CREATE TABLE terms (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terms_type  VARCHAR(30)  NOT NULL,                                   -- SERVICE/PRIVACY/MARKETING 등
    version     VARCHAR(20)  NOT NULL,
    title       VARCHAR(100) NOT NULL,
    content_url VARCHAR(500) NOT NULL,
    required    BOOLEAN      NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT now(),

    CONSTRAINT uk_terms_type_version UNIQUE (terms_type, version)
);

CREATE TABLE user_terms_agreement (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   BIGINT    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    terms_id  BIGINT    NOT NULL REFERENCES terms (id),
    agreed    BOOLEAN   NOT NULL,                                        -- 동의/철회 이력 (행 누적)
    agreed_at TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX ix_uta_user_terms ON user_terms_agreement (user_id, terms_id, agreed_at DESC);

-- ---------- 콘텐츠 기준 데이터 ----------

CREATE TABLE category (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(30) NOT NULL UNIQUE,                           -- 정치, 경제 ...
    display_order INT         NOT NULL,
    active        BOOLEAN     NOT NULL DEFAULT TRUE
);

CREATE TABLE user_interest_category (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    category_id BIGINT    NOT NULL REFERENCES category (id),
    created_at  TIMESTAMP NOT NULL DEFAULT now(),

    CONSTRAINT uk_user_interest_category UNIQUE (user_id, category_id)
);

CREATE TABLE user_notification_setting (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    notification_type VARCHAR(30) NOT NULL,                              -- COMMUTE 등 (유형 목록 확정 필요)
    enabled           BOOLEAN     NOT NULL DEFAULT TRUE,
    updated_at        TIMESTAMP   NOT NULL DEFAULT now(),

    CONSTRAINT uk_user_notification_setting UNIQUE (user_id, notification_type)
);

CREATE TABLE rss_feed (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    press_name      VARCHAR(50)  NOT NULL,
    feed_url        VARCHAR(500) NOT NULL UNIQUE,
    rss_category    VARCHAR(50),
    active          BOOLEAN      NOT NULL DEFAULT TRUE,                  -- 접근 불가 시 비활성
    last_fetched_at TIMESTAMP,
    created_at      TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at      TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE category_mapping (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feed_id      BIGINT      NOT NULL REFERENCES rss_feed (id) ON DELETE CASCADE,
    rss_category VARCHAR(50) NOT NULL,                                   -- 언론사 원본 카테고리
    category_id  BIGINT      NOT NULL REFERENCES category (id),

    CONSTRAINT uk_category_mapping UNIQUE (feed_id, rss_category)
);

CREATE TABLE article (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feed_id           BIGINT        NOT NULL REFERENCES rss_feed (id),
    category_id       BIGINT        REFERENCES category (id),            -- 매핑 전 NULL
    guid              VARCHAR(500),                                      -- 중복 판별 1순위
    original_url      VARCHAR(1000) NOT NULL,                            -- GUID 없을 때 중복 판별
    title             VARCHAR(300)  NOT NULL,
    press_name        VARCHAR(50)   NOT NULL,                            -- 수집 시점 값
    rss_category      VARCHAR(50),
    published_at      TIMESTAMP     NOT NULL,
    raw_content       TEXT,                                              -- (RSS-05)
    cleaned_content   TEXT,                                              -- (RSS-06)
    summary_sentence1 VARCHAR(50),                                       -- 핵심 사건·변화 (30자 이내)
    summary_sentence2 VARCHAR(50),                                       -- 배경·원인·수치
    summary_sentence3 VARCHAR(50),                                       -- 결과·영향·전망
    service_date      DATE          NOT NULL,                            -- (RSS-08)
    difficulty        VARCHAR(10),                                       -- (RSS-02)
    reading_minutes   NUMERIC(6, 2),                                     -- 정제 본문 글자수/500 (RSS-09)
    popularity_rank   INT,                                               -- (TALK-01 기준 확정 필요)
    process_status    VARCHAR(20)   NOT NULL DEFAULT 'COLLECTED',
    recommendable     BOOLEAN       NOT NULL DEFAULT FALSE,
    visibility        VARCHAR(20)   NOT NULL DEFAULT 'VISIBLE',          -- (READ-01, LIB-05)
    created_at        TIMESTAMP     NOT NULL DEFAULT now(),
    updated_at        TIMESTAMP     NOT NULL DEFAULT now(),

    CONSTRAINT ck_article_difficulty     CHECK (difficulty IN ('HARD', 'EASY')),
    CONSTRAINT ck_article_process_status CHECK (process_status IN ('COLLECTED', 'CLEANED', 'SUMMARIZED', 'READY', 'FAILED')),
    CONSTRAINT ck_article_visibility     CHECK (visibility IN ('VISIBLE', 'HIDDEN', 'DELETED')),
    CONSTRAINT ck_article_reading        CHECK (reading_minutes >= 0),
    CONSTRAINT ck_article_popularity     CHECK (popularity_rank > 0),
    -- 추천 가능 기사는 카테고리·난이도·읽기시간·요약이 모두 있어야 함
    CONSTRAINT ck_article_recommendable  CHECK (
        NOT recommendable OR (
            category_id IS NOT NULL AND difficulty IS NOT NULL AND reading_minutes IS NOT NULL
            AND summary_sentence1 IS NOT NULL AND summary_sentence2 IS NOT NULL AND summary_sentence3 IS NOT NULL
        )
    )
);
CREATE UNIQUE INDEX uk_article_guid ON article (guid) WHERE guid IS NOT NULL;
CREATE UNIQUE INDEX uk_article_original_url ON article (original_url);
-- 추천 후보 조회 (서비스일 + 카테고리)
CREATE INDEX ix_article_recommend ON article (service_date, category_id) WHERE recommendable AND visibility = 'VISIBLE';

CREATE TABLE quiz (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id  BIGINT       NOT NULL REFERENCES article (id) ON DELETE CASCADE,
    question    VARCHAR(300) NOT NULL,
    choices     JSONB        NOT NULL,                                   -- [{"seq":1,"content":"..."}, ...]
    answer_seq  INT          NOT NULL,                                   -- 정답 선택지 순번
    explanation VARCHAR(500) NOT NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at  TIMESTAMP    NOT NULL DEFAULT now(),

    CONSTRAINT ck_quiz_status     CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT ck_quiz_choices    CHECK (jsonb_typeof(choices) = 'array' AND jsonb_array_length(choices) >= 2),
    CONSTRAINT ck_quiz_answer_seq CHECK (answer_seq BETWEEN 1 AND jsonb_array_length(choices))
);
CREATE INDEX ix_quiz_article ON quiz (article_id);

CREATE TABLE smalltalk (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id   BIGINT       NOT NULL REFERENCES article (id) ON DELETE CASCADE, -- 카테고리는 기사에서 조회
    service_date DATE         NOT NULL,
    hook         VARCHAR(100) NOT NULL,                                  -- 한 줄 (30자 이내 권장)
    followup     VARCHAR(300) NOT NULL,                                  -- 이어서 (1~2문장)
    visibility   VARCHAR(20)  NOT NULL DEFAULT 'VISIBLE',                -- 기반 기사 숨김 시 HIDDEN
    created_at   TIMESTAMP    NOT NULL DEFAULT now(),

    CONSTRAINT ck_smalltalk_visibility CHECK (visibility IN ('VISIBLE', 'HIDDEN'))
);
CREATE INDEX ix_smalltalk_service_date ON smalltalk (service_date);
CREATE INDEX ix_smalltalk_article ON smalltalk (article_id);

CREATE TABLE term (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    definition  VARCHAR(300) NOT NULL,
    description TEXT,
    visibility  VARCHAR(20)  NOT NULL DEFAULT 'VISIBLE',
    created_at  TIMESTAMP    NOT NULL DEFAULT now(),

    CONSTRAINT ck_term_visibility CHECK (visibility IN ('VISIBLE', 'HIDDEN'))
);

CREATE TABLE scrap (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    target_type VARCHAR(20) NOT NULL,
    target_id   BIGINT      NOT NULL,                                    -- article/term/smalltalk ID (FK 없음, 앱에서 정합성 관리)
    created_at  TIMESTAMP   NOT NULL DEFAULT now(),                      -- (LIB-02 정렬 기준)

    CONSTRAINT ck_scrap_target_type CHECK (target_type IN ('ARTICLE', 'TERM', 'SMALLTALK')),
    CONSTRAINT uk_scrap UNIQUE (user_id, target_type, target_id)
);
CREATE INDEX ix_scrap_list ON scrap (user_id, target_type, created_at DESC);
CREATE INDEX ix_scrap_target ON scrap (target_type, target_id);

CREATE TABLE ai_generation_job (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id    BIGINT      NOT NULL REFERENCES article (id) ON DELETE CASCADE,
    job_type      VARCHAR(20) NOT NULL,
    status        VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    attempt_count INT         NOT NULL DEFAULT 0,                        -- 최초 + 재시도 최대 3회
    last_error    TEXT,
    updated_at    TIMESTAMP   NOT NULL DEFAULT now(),

    CONSTRAINT ck_agj_job_type      CHECK (job_type IN ('SUMMARY', 'QUIZ', 'SMALLTALK')),
    CONSTRAINT ck_agj_status        CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED', 'ABANDONED')),
    CONSTRAINT ck_agj_attempt_count CHECK (attempt_count BETWEEN 0 AND 4),
    CONSTRAINT uk_agj_article_type  UNIQUE (article_id, job_type)
);
CREATE INDEX ix_agj_retry ON ai_generation_job (status) WHERE status IN ('PENDING', 'FAILED');

CREATE TABLE batch_run (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_date  DATE        NOT NULL,                                  -- 전일 23:45 수집분
    status        VARCHAR(20) NOT NULL DEFAULT 'RUNNING',
    started_at    TIMESTAMP   NOT NULL DEFAULT now(),
    finished_at   TIMESTAMP,
    error_message TEXT,

    CONSTRAINT ck_batch_run_status   CHECK (status IN ('RUNNING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_batch_run_finished CHECK (status = 'RUNNING' OR finished_at IS NOT NULL)
);
CREATE INDEX ix_batch_run_service_date ON batch_run (service_date);

-- ---------- 노선 (추천 요청 1회 = route 1행) ----------

CREATE TABLE route (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    service_date            DATE          NOT NULL,                      -- KST 04:00 경계
    ride_condition          VARCHAR(10)   NOT NULL,                      -- 스냅샷
    target_minutes          INT           NOT NULL,                      -- 목표 시간 T (스냅샷)
    interest_category_ids   JSONB         NOT NULL DEFAULT '[]',         -- 요청 시점 관심분야 ID 목록
    candidate_total         INT           NOT NULL DEFAULT 0,
    candidate_hard          INT           NOT NULL DEFAULT 0,
    candidate_easy          INT           NOT NULL DEFAULT 0,
    fallback_stage          INT           NOT NULL DEFAULT 0,
    total_estimated_minutes NUMERIC(6, 2) NOT NULL DEFAULT 0,
    status                  VARCHAR(20)   NOT NULL DEFAULT 'CREATED',    -- EMPTY = 선택 기사 0건
    current_seq             INT           NOT NULL DEFAULT 0,            -- 이어보기 (READ-03)
    started_at              TIMESTAMP,                                   -- (RIDE-06)
    completed_at            TIMESTAMP,                                   -- (ARR-01)
    expires_at              TIMESTAMP     NOT NULL,                      -- 서비스일 다음 날 04:00
    created_at              TIMESTAMP     NOT NULL DEFAULT now(),

    CONSTRAINT ck_route_condition    CHECK (ride_condition IN ('SUNNY', 'NORMAL', 'CLOUDY', 'RAINY')),
    CONSTRAINT ck_route_status       CHECK (status IN ('EMPTY', 'CREATED', 'IN_PROGRESS', 'COMPLETED', 'EXPIRED')),
    CONSTRAINT ck_route_target       CHECK (target_minutes > 0),
    CONSTRAINT ck_route_fallback     CHECK (fallback_stage BETWEEN 0 AND 2),
    CONSTRAINT ck_route_candidates   CHECK (candidate_hard >= 0 AND candidate_easy >= 0 AND candidate_total = candidate_hard + candidate_easy),
    CONSTRAINT ck_route_estimated    CHECK (total_estimated_minutes >= 0),
    CONSTRAINT ck_route_current_seq  CHECK (current_seq >= 0),
    CONSTRAINT ck_route_interest     CHECK (jsonb_typeof(interest_category_ids) = 'array'),
    CONSTRAINT ck_route_completed_at CHECK (status <> 'COMPLETED' OR completed_at IS NOT NULL)
);
CREATE INDEX ix_route_user_date ON route (user_id, service_date DESC);

CREATE TABLE route_article (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id        BIGINT        NOT NULL REFERENCES route (id) ON DELETE CASCADE,
    article_id      BIGINT        NOT NULL REFERENCES article (id),
    seq             INT           NOT NULL,                              -- 노선 내 순번 (랜덤 셔플)
    difficulty      VARCHAR(10)   NOT NULL,                              -- 스냅샷
    reading_minutes NUMERIC(6, 2) NOT NULL,                              -- 스냅샷
    read_at         TIMESTAMP,                                           -- 열람(=완독) 시각 (READ-02)

    CONSTRAINT uk_ra_seq        UNIQUE (route_id, seq),
    CONSTRAINT uk_ra_article    UNIQUE (route_id, article_id),
    CONSTRAINT ck_ra_diff_value CHECK (difficulty IN ('HARD', 'EASY')),
    CONSTRAINT ck_ra_seq        CHECK (seq >= 1),
    CONSTRAINT ck_ra_reading    CHECK (reading_minutes >= 0)
);
CREATE INDEX ix_ra_article ON route_article (article_id);

CREATE TABLE quiz_answer (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id     BIGINT    NOT NULL REFERENCES route (id) ON DELETE CASCADE, -- 유저는 route 로 식별
    quiz_id      BIGINT    NOT NULL REFERENCES quiz (id),
    selected_seq INT       NOT NULL,
    is_correct   BOOLEAN   NOT NULL,                                     -- 스냅샷
    answered_at  TIMESTAMP NOT NULL DEFAULT now(),

    CONSTRAINT uk_quiz_answer       UNIQUE (route_id, quiz_id),
    CONSTRAINT ck_quiz_answer_seq   CHECK (selected_seq >= 1)
);
CREATE INDEX ix_quiz_answer_quiz ON quiz_answer (quiz_id);
