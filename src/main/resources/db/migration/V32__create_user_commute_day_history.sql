-- =========================================================
-- 이동 요일 변경 이력 (HOME-02 스트릭 기준)
--  - 스트릭은 그 서비스일에 이동하는 요일(이동시간 5분 이상)로 정한 날을 대상으로 센다
--  - 요일 설정을 바꾸면 다음 서비스일부터 적용하는 행을 남긴다. 그날 바꾼 설정은 그날 스트릭에 반영하지 않는다
--  - 처음 바꿀 때는 바꾸기 전 설정을 1970-01-01부터 적용하는 행으로 먼저 남긴다(배포 전 기간은 그 설정을 따른다)
--  - 이력이 없는 회원은 users의 현재 요일 설정을 모든 날짜에 적용한다
--  - commute_days: 이동하는 요일 비트(월=1, 화=2, 수=4, 목=8, 금=16, 토=32, 일=64). 0이면 이동하는 요일이 없다
-- =========================================================

CREATE TABLE user_commute_day_history (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    effective_from DATE      NOT NULL,
    commute_days   SMALLINT  NOT NULL,
    created_at     TIMESTAMP NOT NULL,
    CONSTRAINT uk_user_commute_day_history UNIQUE (user_id, effective_from),
    CONSTRAINT ck_user_commute_day_history_days CHECK (commute_days BETWEEN 0 AND 127)
);
