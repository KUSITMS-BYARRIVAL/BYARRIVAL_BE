-- ---------- 노선 운행: 기사 완독과 이용 이벤트 로그 (READ-02, ARR-01, LOG-01) ----------
-- 완독은 [기사 보러가기]를 누른 시점이다. 원문 열기에 실패해도 완독으로 친다.
-- route_card.read_at이 사용자의 읽음 이력이다(삭제하지 않고 보관, 추후 개인화에 활용).
ALTER TABLE route_card
    ADD COLUMN read_at TIMESTAMP,
    ADD CONSTRAINT ck_route_card_read_carted CHECK (read_at IS NULL OR cart_order IS NOT NULL);

-- 이용 이벤트 로그. 노스타 지표(주간 완주일수)와 추천 품질 분석에 쓴다. 6개월 보관 후 파기한다.
--  - ARTICLE_READ: 기사 열람(완독), ROUTE_COMPLETED: 노선 완주. service_date는 노선의 서비스일
--  - APP_ACCESS: 앱 접속(나의 기록 캘린더용). service_date는 KST 자정 기준 날짜이며 이 티켓에서는 아직 쓰지 않는다
--  - 같은 이벤트는 한 번만 남긴다(재시도·연타 대비)
CREATE TABLE usage_event_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    route_id     BIGINT      REFERENCES route (id) ON DELETE CASCADE,
    article_id   BIGINT      REFERENCES article (id),
    event_type   VARCHAR(30) NOT NULL,
    service_date DATE        NOT NULL,
    occurred_at  TIMESTAMP   NOT NULL,
    created_at   TIMESTAMP   NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),

    CONSTRAINT ck_usage_event_type CHECK (event_type IN ('ARTICLE_READ', 'ROUTE_COMPLETED', 'APP_ACCESS')),
    CONSTRAINT ck_usage_event_article_read CHECK (event_type <> 'ARTICLE_READ' OR (route_id IS NOT NULL AND article_id IS NOT NULL)),
    CONSTRAINT ck_usage_event_route_completed CHECK (event_type <> 'ROUTE_COMPLETED' OR route_id IS NOT NULL)
);
CREATE UNIQUE INDEX uk_usage_event_article_read ON usage_event_log (user_id, route_id, article_id)
    WHERE event_type = 'ARTICLE_READ';
CREATE UNIQUE INDEX uk_usage_event_route_completed ON usage_event_log (user_id, route_id)
    WHERE event_type = 'ROUTE_COMPLETED';
CREATE UNIQUE INDEX uk_usage_event_app_access ON usage_event_log (user_id, service_date)
    WHERE event_type = 'APP_ACCESS';
CREATE INDEX ix_usage_event_user_date ON usage_event_log (user_id, service_date);
CREATE INDEX ix_usage_event_occurred_at ON usage_event_log (occurred_at);
