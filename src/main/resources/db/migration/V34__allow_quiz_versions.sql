-- =========================================================
-- 퀴즈 재생성 버전 관리 (ARTICLE-06)
--  - 재생성하면 기존 퀴즈는 INACTIVE로 남기고 새 퀴즈를 ACTIVE로 추가한다. 이전 버전은 지우지 않는다
--  - 이미 퀴즈를 받은 노선(route_quiz)은 받은 버전을 그대로 쓰므로 사용자 응답 기록이 지워지지 않는다
--  - 기사당 퀴즈 1개였던 유일 제약을 "기사당 ACTIVE 퀴즈 1개"로 바꾼다. 배치가 제약 이름으로 중복을 알아보므로 이름은 그대로 둔다
-- =========================================================

DROP INDEX uk_quiz_article;
CREATE UNIQUE INDEX uk_quiz_article ON quiz (article_id) WHERE status = 'ACTIVE';
