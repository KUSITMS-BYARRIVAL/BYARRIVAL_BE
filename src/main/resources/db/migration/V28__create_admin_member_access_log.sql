-- =========================================================
-- 어드민의 회원 상세 열람 기록 (MEMBER-04)
--  - 회원을 파기해도 "누가 언제 열람했는지"가 남도록 user_id에 외래 키를 걸지 않는다
--  - 보관 기간이 확정되지 않아 자동 파기는 아직 하지 않는다
-- =========================================================

CREATE TABLE admin_member_access_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id    BIGINT    NOT NULL REFERENCES admin_account (id),
    user_id     BIGINT    NOT NULL,
    accessed_at TIMESTAMP NOT NULL
);
CREATE INDEX ix_admin_member_access_log_user ON admin_member_access_log (user_id, accessed_at DESC);
CREATE INDEX ix_admin_member_access_log_admin ON admin_member_access_log (admin_id, accessed_at DESC);
