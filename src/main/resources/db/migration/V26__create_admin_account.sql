-- =========================================================
-- 어드민 계정 (ADM-01). 앱 회원(users)과 분리한다
--  - 가입 화면이 없어 계정은 SQL로 등록한다. password_hash는 BCrypt 값이다
--  - token_version이 바뀌면 이미 발급한 어드민 토큰은 모두 무효가 된다
-- =========================================================

CREATE TABLE admin_account (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email              VARCHAR(254) NOT NULL,
    password_hash      VARCHAR(100) NOT NULL,
    role               VARCHAR(20)  NOT NULL DEFAULT 'OPERATOR',
    active             BOOLEAN      NOT NULL DEFAULT TRUE,
    token_version      INTEGER      NOT NULL DEFAULT 0,
    created_at         TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),
    updated_at         TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),

    CONSTRAINT uk_admin_account_email UNIQUE (email),
    CONSTRAINT ck_admin_account_email_lower CHECK (email = lower(email)),
    CONSTRAINT ck_admin_account_role CHECK (role IN ('OPERATOR', 'EDITOR'))
);
