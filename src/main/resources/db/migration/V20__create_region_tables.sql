-- 근무 지역 변경 이력(MY-12). 온보딩에서 처음 고를 때와 바꿀 때마다 바뀐 뒤의 지역을 남긴다
CREATE TABLE user_region_history (
    id                BIGINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    region_sigungu_id INTEGER   NOT NULL REFERENCES region_sigungu (id),
    created_at        TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),
    updated_at        TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul')
);
CREATE INDEX ix_user_region_history_user ON user_region_history (user_id);
