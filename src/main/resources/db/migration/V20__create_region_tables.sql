-- ---------- 근무 지역 (ONB-12·ONB-13·MY-12) ----------
-- 온보딩·마이에서 근무·통학·주 이동 지역을 시/도 → 시/군/구 하나로 고른다. 지금은 수집만 하고 노출 기준으로 쓰지 않는다.
-- 시/도는 명세·디자인대로 17개다(2026-11-16 결정). 2026-07-01 광주·전남 통합 뒤에도 사용자가 익숙한 이름으로 따로 고른다.
-- 서울·광역시는 자치구, 도는 시·군 단위다. 일반구가 있는 시(수원·성남·고양 등)는 시까지만 고른다(2026-11-16 결정).
-- 인천은 2026-07-01 개편 뒤 구(제물포구·영종구·서해구·검단구)를 쓴다. 세종은 시/군/구 없이 "세종특별자치시" 하나다.
-- "○○전체" 선택지는 없다. id는 서비스가 정한 값이며 행정표준코드가 아니다. 나중에 권역으로 묶을 때는 별도 매핑 테이블을 둔다(ONB-13).
CREATE TABLE region_sido (
    id         SMALLINT    PRIMARY KEY,
    name       VARCHAR(10) NOT NULL,
    full_name  VARCHAR(20) NOT NULL,

    CONSTRAINT uk_region_sido_name UNIQUE (name)
);

-- id는 시/도 id × 100 + 이름순 번호다
CREATE TABLE region_sigungu (
    id       INTEGER     PRIMARY KEY,
    sido_id  SMALLINT    NOT NULL REFERENCES region_sido (id),
    name     VARCHAR(20) NOT NULL,

    CONSTRAINT uk_region_sigungu_name UNIQUE (sido_id, name)
);

