-- ---------- 오늘의 퀴즈 (AI-03, AI-04, QUIZ-01~03) ----------
-- 퀴즈는 배치에서 추천 후보 기사마다 1문제(3지선다)를 만든다. 다시 돌려도 기사당 1문제만 남게 한다.
CREATE UNIQUE INDEX uk_quiz_article ON quiz (article_id);

-- 노선의 퀴즈 3문제와 사용자 응답. 처음 퀴즈를 열 때 완독한 기사 중에서 골라 고정하고(최대 3문제),
-- 응답은 문제당 한 번만 저장한다(중복 제출 방지). 안 푼 문제는 다시 들어오면 이어서 푼다.
CREATE TABLE route_quiz (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id     BIGINT    NOT NULL REFERENCES route (id) ON DELETE CASCADE,
    quiz_id      BIGINT    NOT NULL REFERENCES quiz (id) ON DELETE CASCADE,
    quiz_order   INT       NOT NULL,
    selected_seq INT,
    correct      BOOLEAN,
    answered_at  TIMESTAMP,
    created_at   TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),

    CONSTRAINT uk_route_quiz_order UNIQUE (route_id, quiz_order),
    CONSTRAINT uk_route_quiz_quiz UNIQUE (route_id, quiz_id),
    CONSTRAINT ck_route_quiz_answer CHECK ((selected_seq IS NULL) = (answered_at IS NULL)
        AND (selected_seq IS NULL) = (correct IS NULL))
);
